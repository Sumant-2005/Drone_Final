"""Native Simulink subsystems. Coordinates describe the block centres on a grid."""
def horizontal(g):
    ref=g.input('Forward and right demand',1,0,0)
    ne=g.input('North and east velocity',2,0,2)
    yaw=g.input('Heading',3,0,3)
    measured=g.group('Rotate velocity into body',1,2,[ne,yaw],rotate,inverse=True)
    err=g.op('Sum','Velocity error',2,0,[ref,measured],Inputs='+-')
    accel=g.gain('Velocity gain',3,0,err,'df_p.velocity_gain_per_s')
    drag=g.gain('Drag feedforward',3,1,ref,'df_p.linear_drag_N_per_m_s/df_p.mass_kg')
    total=g.op('Sum','Requested acceleration',4,0,[accel,drag],Inputs='++')
    limited=g.group('Bound horizontal acceleration',5,0,[total],limit_norm)
    tilt=g.group('Convert acceleration to tilt',6,0,[limited],tilt_angles)
    g.output('Roll and pitch demand',1,7,0,tilt)

def rotate(g,inverse=False):
    v=g.input('Planar components',1,0,1)
    u,w=g.split('Components',1,1,v,[1,1])
    yaw=g.input('Yaw',2,0,3)
    c=g.trig('Cosine',1,3,yaw,'cos');s=g.trig('Sine',1,4,yaw,'sin')
    cu=g.prod('First times cosine',2,0,u,c)
    sw=g.prod('Second times sine',2,1,w,s)
    su=g.prod('First times sine',2,2,u,s)
    cw=g.prod('Second times cosine',2,3,w,c)
    x=g.op('Sum','Rotated first',3,0,[cu,sw],Inputs='++' if inverse else '+-')
    y=g.op('Sum','Rotated second',3,2,[cw,su],Inputs='+-' if inverse else '++')
    g.output('Rotated vector',1,5,1,g.mux('Join components',4,1,[x,y]))

def limit_norm(g):
    v=g.input('Acceleration',1,0,0)
    sq=g.op('DotProduct','Squared magnitude',1,1,[v,v])
    norm=g.op('Sqrt','Magnitude',2,1,[sq])
    ratio=g.gain('Relative to limit',3,1,norm,'1/df_p.max_accel_m_s2')
    divisor=g.sat('Minimum divisor of one',4,1,ratio,'1','inf')
    g.output('Bounded acceleration',1,6,0,g.divide('Scale vector',5,0,v,divisor))

def tilt_angles(g):
    v=g.input('Forward and right acceleration',1,0,0)
    normalized=g.gain('Divide by gravity',1,0,v,'1/df_p.gravity_m_s2')
    angles=g.trig('Tilt angles',2,0,normalized,'atan')
    pair=g.matrix('Right to roll and forward to pitch',3,0,angles,'[0 1;-1 0]')
    g.output('Roll and pitch',1,4,0,pair)

def vertical(g):
    up=g.input('Climb demand',1,0,0);height=g.input('Height demand',2,0,1)
    down=g.input('Down position',3,0,2);vd=g.input('Down velocity',4,0,3)
    angles=g.input('Roll and pitch',5,0,5)
    err=g.op('Sum','Height error',1,1,[height,down],Inputs='++')
    corr=g.gain('Height gain',2,1,err,'df_p.height_gain_per_s')
    climb=g.op('Sum','Requested climb',3,0,[up,corr],Inputs='++')
    dv=g.op('Sum','Climb error',4,1,[climb,vd],Inputs='++')
    force=g.gain('Climb gain times mass',5,1,dv,'df_p.mass_kg*df_p.climb_gain_per_s')
    ff=g.gain('Vertical drag feedforward',5,0,climb,'df_p.linear_drag_N_per_m_s')
    weight=g.constant('Weight',5,2,'df_p.mass_kg*df_p.gravity_m_s2')
    vertical_force=g.op('Sum','Upward force',6,1,[force,ff,weight],Inputs='+++')
    cosines=g.trig('Roll and pitch cosines',2,5,angles,'cos')
    cr,cp=g.split('Cosine components',3,5,cosines,[1,1])
    proj=g.prod('Vertical projection',4,5,cr,cp)
    bounded=g.sat('Projection floor',5,5,proj,'0.5','1')
    g.output('Collective thrust',1,8,1,g.divide('Tilt compensation',7,1,vertical_force,bounded))

def moments(g):
    angles=g.input('Demanded roll and pitch',1,0,0)
    actual=g.input('Measured roll and pitch',2,0,1)
    yaw=g.input('Demanded yaw rate',3,0,2)
    rates=g.input('Body rates',4,0,3)
    err=g.op('Sum','Angle error',1,0,[angles,actual],Inputs='+-')
    rp=g.gain('Angle gain',2,0,err,'df_p.tilt_gain_per_s')
    ref=g.mux('Desired body rates',3,1,[rp,yaw])
    e=g.op('Sum','Rate error',4,1,[ref,rates],Inputs='+-')
    m=g.matrix('Inertia times rate gain',5,1,e,'diag(df_p.inertia_kg_m2(:).*df_p.rate_gain_per_s(:))')
    ff=g.gain('Rotational drag',5,3,rates,'df_p.angular_drag_Nm_per_rad_s')
    g.output('Body moments',1,7,1,g.op('Sum','Requested moments',6,1,[m,ff],Inputs='++'))

def allocation_limit(g):
    raw=g.input('Raw rotor thrusts',1,0,0)
    mean=g.matrix('Mean rotor thrust',1,1,raw,'ones(1,4)/4')
    common=g.sat('Available collective',2,2,mean,'0','df_p.max_thrust')
    delta=g.op('Sum','Differential thrusts',2,0,[raw,mean],Inputs='+-')
    scale=g.group('Available moment authority',3,1,[delta,common],authority)
    diff=g.prod('Scale differences',4,0,delta,scale)
    added=g.op('Sum','Restore collective',5,1,[common,diff],Inputs='++')
    g.output('Feasible thrusts',1,7,1,g.sat('Thrust bounds',6,1,added,'0','df_p.max_thrust'))

def authority(g):
    d=g.input('Differential thrusts',1,0,1);mean=g.input('Collective per rotor',2,0,3)
    peak=g.op('MinMax','Largest increase',1,0,[d],Function='max',Inputs='1')
    low=g.op('MinMax','Largest decrease',1,2,[d],Function='min',Inputs='1')
    neg=g.gain('Magnitude of decrease',2,2,low,'-1')
    cap=g.constant('Maximum thrust',1,4,'df_p.max_thrust')
    room=g.op('Sum','Upward room',2,4,[cap,mean],Inputs='+-')
    up=g.sat('Positive increase divisor',3,0,peak,'eps','inf')
    down=g.sat('Positive decrease divisor',3,2,neg,'eps','inf')
    a=g.divide('Increase scale',4,0,room,up);b=g.divide('Decrease scale',4,2,mean,down)
    scale=g.op('MinMax','Smaller scale',5,1,[a,b],Function='min',Inputs='2')
    g.output('Scale',1,7,1,g.sat('Unit scale limit',6,1,scale,'0','1'))

def projection(g):
    ang=g.input('Euler angles',1,0,1)
    phi,theta,yaw=g.split('Roll pitch yaw',1,1,ang,[1,1,1])
    cf=g.trig('Cos roll',2,0,phi,'cos');sf=g.trig('Sin roll',2,1,phi,'sin')
    st=g.trig('Sin pitch',2,2,theta,'sin');ct=g.trig('Cos pitch',2,3,theta,'cos')
    x=g.prod('Forward component',3,0,cf,st)
    y=g.gain('Right component',3,1,sf,'-1')
    z=g.prod('Down component',3,3,cf,ct)
    xy=g.mux('Planar projection',4,1,[x,y])
    ne=g.group('Rotate to north and east',5,1,[xy,yaw],rotate)
    g.output('Body down axis in NED',1,7,1,g.mux('Direction vector',6,1,[ne,z]))

def acceleration(g):
    thrust=g.input('Total thrust',1,0,0);euler=g.input('Euler angles',2,0,1);v=g.input('NED velocity',3,0,3)
    z=g.group('Body thrust direction',1,1,[euler],projection)
    f=g.prod('Thrust along body down',2,0,thrust,z)
    drag=g.gain('Linear drag',2,3,v,'df_p.linear_drag_N_per_m_s')
    resist=g.op('Sum','Thrust and drag',3,1,[f,drag],Inputs='++')
    acc=g.gain('Force to acceleration',4,1,resist,'1/df_p.mass_kg')
    grav=g.constant('NED gravity',4,0,'[0;0;df_p.gravity_m_s2]')
    g.output('NED acceleration',1,6,0,g.op('Sum','Gravity minus thrust and drag',5,0,[grav,acc],Inputs='+-'))

def angular(g):
    mom=g.input('Moments',1,0,0);w=g.input('Body rates',2,0,2)
    pp,q,r=g.split('Roll pitch yaw rates',1,2,w,[1,1,1])
    qr=g.prod('Pitch times yaw',2,1,q,r);pr=g.prod('Roll times yaw',2,2,pp,r);pq=g.prod('Roll times pitch',2,3,pp,q)
    pairs=g.mux('Rate products',3,2,[qr,pr,pq])
    gy=g.matrix('Gyroscopic moment',4,2,pairs,'df_p.gyro_gain')
    drag=g.gain('Angular drag',4,3,w,'df_p.angular_drag_Nm_per_rad_s')
    net=g.op('Sum','Net body moment',5,1,[mom,gy,drag],Inputs='+--')
    g.output('Angular acceleration',1,7,1,g.matrix('Inverse inertia',6,1,net,'diag(1./df_p.inertia_kg_m2(:))'))

def kinematics(g):
    angles=g.input('Euler angles',1,0,0);rates=g.input('Body rates',2,0,2)
    phi,theta,_=g.split('Roll pitch yaw',1,0,angles,[1,1,1],unused=[3])
    pp,q,r=g.split('Body rate components',1,2,rates,[1,1,1])
    sf=g.trig('Sin roll',2,0,phi,'sin');cf=g.trig('Cos roll',2,1,phi,'cos')
    ct=g.trig('Cos pitch',2,3,theta,'cos');tn=g.trig('Tan pitch',2,4,theta,'tan')
    qs=g.prod('Pitch sine term',3,0,q,sf);rc=g.prod('Yaw cosine term',3,1,r,cf)
    qc=g.prod('Pitch cosine term',3,2,q,cf);rs=g.prod('Yaw sine term',3,3,r,sf)
    pair=g.op('Sum','Rotated yaw component',4,0,[qs,rc],Inputs='++')
    pd=g.op('Sum','Pitch derivative',4,2,[qc,rs],Inputs='+-')
    add=g.prod('Rotation coupling',5,0,pair,tn);yd=g.divide('Yaw derivative',5,3,pair,ct)
    rd=g.op('Sum','Roll derivative',6,0,[pp,add],Inputs='++')
    g.output('Euler derivatives',1,8,1,g.mux('Euler rates',7,1,[rd,pd,yd]))

def motors(g):
    ref=g.input('Speed references',1,0,0)
    g.add('Integrator','Rotor speed',620,68,115,48,InitialCondition='df_p.x0(13:16)')
    err=g.op('Sum','Speed error',1,1,[ref,'Rotor speed'],Inputs='+-')
    slope=g.gain('Inverse motor time constant',2,1,err,'1/df_p.speed_lag_s')
    g.wire(slope,'Rotor speed')
    g.output('Speed',1,4,0,'Rotor speed')
    sq=g.prod('Speed squared',4,1,'Rotor speed','Rotor speed')
    thrust=g.gain('Propeller thrust',5,1,sq,'df_p.kT')
    g.output('Total force and moments',2,7,1,g.matrix('Thrust to body loads',6,1,thrust,'df_p.effectiveness'))

def plant(g):
    ref=g.input('Speed references',1,0,0)
    rotor=g.group('Ideal rotor dynamics',1,0,[ref],motors)
    force,mom=g.split('Force and moments',2,1,(rotor,2),[1,3])
    for name,row,ic in [('Position',0,'1:3'),('Velocity',1,'4:6'),('Euler angles',2,'7:9'),('Body rates',3,'10:12')]:
        g.add('Integrator',name,1000,40+row*108,110,42,InitialCondition='df_p.x0('+ic+')')
    acc=g.group('Linear acceleration',3,1,[force,'Euler angles','Velocity'],acceleration)
    eul=g.group('Euler angle kinematics',3,2,['Euler angles','Body rates'],kinematics)
    spin=g.group('Angular acceleration',3,3,[mom,'Body rates'],angular)
    for src,dest in [(acc,'Velocity'),('Velocity','Position'),(eul,'Euler angles'),(spin,'Body rates')]:g.wire(src,dest)
    state=g.mux('Combine flight state',6,1,['Position','Velocity','Euler angles','Body rates',rotor])
    sampled=g.op('ZeroOrderHold','Flight computer sample',7,1,[state],SampleTime='df_p.step_s')
    g.output('Sampled state',1,8,1,sampled)

def controller(g):
    cmd=g.input('Commands',1,0,0);x=g.input('Sampled state',2,0,3)
    pair,up,height,yaw=g.split('Movement references',1,0,cmd,[2,1,1,1])
    _,down,ne,vd,angles,heading,rates,_=g.split('Feedback channels',1,3,x,[2,1,2,1,2,1,3,4],unused=[1,8])
    tilt=g.group('Horizontal velocity',3,0,[pair,ne,heading],horizontal)
    collective=g.group('Height and climb',3,2,[up,height,down,vd,angles],vertical)
    m=g.group('Attitude and body rates',5,0,[tilt,angles,yaw,rates],moments)
    g.output('Requested loads',1,7,1,g.mux('Collective roll pitch yaw',6,1,[collective,m]))

def instruments(g):
    state=g.input('State',1,0,1)
    ne,down,vxy,_,angles,_,rot=g.split('State components',1,1,state,[2,1,2,1,3,3,4],unused=[4,6])
    _,yaw=g.split('Heading channel',2,0,angles,[2,1],unused=[1])
    vb=g.group('Velocity in body axes',3,0,[vxy,yaw],rotate,inverse=True)
    vf,_=g.split('Forward component',4,0,vb,[1,1],unused=[2])
    height=g.gain('Height above ground',3,1,down,'-1')
    deg=g.gain('Radians to degrees',3,2,angles,'180/pi')
    rpm=g.gain('Actual rotor rpm',3,3,rot,'30/pi')
    sq=g.prod('Rotor speed squared',2,4,rot,rot)
    q=g.gain('Aerodynamic torque',3,4,sq,'df_p.kQ')
    g.output('Measurements',1,6,2,g.mux('Instrument channels',5,2,[vf,height,ne,deg,rpm,q]))
